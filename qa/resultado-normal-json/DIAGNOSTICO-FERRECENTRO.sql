/* SOLO LECTURA. Ejecutar en la base real de Ferrecentro, con autorizacion
   de su responsable. No emitir ni invocar procedimientos de reserva/envio.
   El e-NCF por si solo no identifica la empresa/base; comprobar primero.
*/
SELECT V.NUMERO AS TRN, V.CIA_KEY, C.RNC_NUMERO,
       V.SERIE_NCF_ASIGNADO, N.NUMERO_NCF, N.DGII_STATUS,
       N.TRACK_ID, N.DGII_MENSAJE, N.ULTIMO_INTENTO
FROM VENTAS_MAST V
JOIN COMPANIA C ON C.CODIGO=V.CIA_KEY
JOIN NCF_ASIGNADOS N ON N.SERIE=V.SERIE_NCF_ASIGNADO
WHERE N.NUMERO_NCF='E320000000803';

SELECT T.ID,T.TRN,T.ENCF,T.CODIGO_SEGURIDAD,T.FECHA_EMISION,
       T.MONTO_TOTAL,T.URL_IMAGE,T.FECHA_CREACION
FROM ECF_TIMBRE_LOG T
JOIN VENTAS_MAST V ON V.NUMERO=T.TRN
JOIN NCF_ASIGNADOS N ON N.SERIE=V.SERIE_NCF_ASIGNADO
WHERE N.NUMERO_NCF='E320000000803'
ORDER BY T.ID DESC;
