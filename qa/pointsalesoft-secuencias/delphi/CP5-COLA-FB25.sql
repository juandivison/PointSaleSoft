/* Firebird 2.5. Migracion opt-in para REMOTO. Ejecutar solo en QA.
   No altera procedimientos ni tablas LOCAL.
   REQUEST_ID se confirma antes del primer contacto HTTPS.
   NUMERO_TRN se vincula a la venta comercial una vez persistida. */
CREATE TABLE ECF_SEC_SOLICITUD (
    REQUEST_ID VARCHAR(36) CHARACTER SET ASCII NOT NULL,
    RNC_EMISOR VARCHAR(11) CHARACTER SET ASCII NOT NULL,
    AMBIENTE VARCHAR(4) CHARACTER SET ASCII NOT NULL,
    SUCURSAL_ID VARCHAR(64) CHARACTER SET ASCII NOT NULL,
    DOCUMENTO_CLAVE VARCHAR(128) CHARACTER SET ASCII NOT NULL,
    TIPO_ECF CHAR(3) CHARACTER SET ASCII NOT NULL,
    NUMERO_TRN INTEGER,
    ESTADO VARCHAR(24) CHARACTER SET ASCII NOT NULL,
    RESERVA_ID VARCHAR(20) CHARACTER SET ASCII,
    LOTE_ID VARCHAR(20) CHARACTER SET ASCII,
    ENCF VARCHAR(13) CHARACTER SET ASCII,
    FECHA_VENCE DATE,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTUALIZADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ECF_SEC_SOLICITUD PRIMARY KEY (REQUEST_ID),
    CONSTRAINT UQ_ECF_SEC_DOCUMENTO UNIQUE
      (RNC_EMISOR, AMBIENTE, SUCURSAL_ID, DOCUMENTO_CLAVE),
    CONSTRAINT CK_ECF_SEC_ESTADO CHECK
      (ESTADO IN ('PENDIENTE_CONCILIACION', 'RESERVADA')),
    CONSTRAINT CK_ECF_SEC_RESULTADO CHECK (
      (ESTADO='PENDIENTE_CONCILIACION' AND ENCF IS NULL AND RESERVA_ID IS NULL
        AND LOTE_ID IS NULL AND FECHA_VENCE IS NULL) OR
      (ESTADO='RESERVADA' AND ENCF IS NOT NULL AND RESERVA_ID IS NOT NULL
        AND LOTE_ID IS NOT NULL AND FECHA_VENCE IS NOT NULL)
    )
);
