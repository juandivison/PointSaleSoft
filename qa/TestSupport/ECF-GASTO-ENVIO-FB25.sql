CREATE TABLE ECF_GASTO_ENVIO (
 ID INTEGER NOT NULL,
 CIA_KEY INTEGER NOT NULL,
 TRN INTEGER NOT NULL,
 TIPO_CF SMALLINT NOT NULL,
 ENCF VARCHAR(20) NOT NULL,
 ESTADO VARCHAR(32) NOT NULL,
 TRACK_ID VARCHAR(100),
 MENSAJE VARCHAR(1024),
 INTENTOS SMALLINT DEFAULT 0 NOT NULL,
 CODIGO_SEGURIDAD VARCHAR(64),
 FECHA_EMISION TIMESTAMP,
 FECHA_FIRMA TIMESTAMP,
 MONTO_TOTAL NUMERIC(18,2),
 URL_IMAGE VARCHAR(1024),
 XML_FIRMADO VARCHAR(1024),
 FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FECHA_UPDATE TIMESTAMP,
 CONSTRAINT PK_ECF_GASTO_ENVIO PRIMARY KEY (ID),
 CONSTRAINT UQ_ECF_GASTO_ENVIO_ENCF UNIQUE (CIA_KEY,ENCF)
);
CREATE INDEX IX_ECF_GASTO_ENVIO_ESTADO ON ECF_GASTO_ENVIO(ESTADO);
CREATE INDEX IX_ECF_GASTO_ENVIO_TRN ON ECF_GASTO_ENVIO(CIA_KEY,TRN);
