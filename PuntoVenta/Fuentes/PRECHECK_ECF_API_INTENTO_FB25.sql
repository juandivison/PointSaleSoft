   Verificar UNIQUE exacto sobre (RNC_EMISOR, NUMERO_TRN), sin otros campos.
   Si no existe, NO activar emisión multiestacion hasta migración revisada.
*/
SELECT
  TRIM(I.RDB$INDEX_NAME) AS INDICE,
  I.RDB$UNIQUE_FLAG AS ES_UNICO,
  I.RDB$INDEX_INACTIVE AS ESTA_INACTIVO,
  S.RDB$FIELD_POSITION AS POSICION,
  TRIM(S.RDB$FIELD_NAME) AS CAMPO
FROM RDB$INDICES I
JOIN RDB$INDEX_SEGMENTS S
  ON S.RDB$INDEX_NAME = I.RDB$INDEX_NAME
WHERE I.RDB$RELATION_NAME = 'ECF_API_INTENTO'
ORDER BY I.RDB$INDEX_NAME, S.RDB$FIELD_POSITION;
