/* A. Factura, NCF y campos relevantes para estado fiscal */
SELECT
  V.NUMERO AS TRN,
  V.STATUS AS STATUS_VENTA,
  V.ESTADO_VENTA,
  V.SERIE_NCF_ASIGNADO,
  V.REF_TRN_ORIGEN,
  V.REF_NCF_ORIGEN,
  V.REF_FECHA_ORIGEN,
  V.IDDGII_MOTIVO_NCR,
  N.SERIE AS SERIE_NCF,
  N.NUMERO_NCF,
  N.DGII_STATUS,
  N.TRACK_ID,
  N.FECHA_ESTADO,
  N.LAST_ERROR,
  N.REINTENTOS,
  N.BLOQUEADO
FROM VENTAS_MAST V
JOIN NCF_ASIGNADOS N ON N.SERIE = V.SERIE_NCF_ASIGNADO
WHERE N.NUMERO_NCF = 'E310000000802';

/* B. Timbre existente (si fue recuperado en CP13.13) */
SELECT T.ID, T.TRN, T.ENCF, T.CODIGO_SEGURIDAD,
       T.FECHA_EMISION, T.MONTO_TOTAL, T.URL_IMAGE, T.FECHA_CREACION
FROM ECF_TIMBRE_LOG T
WHERE T.ENCF = 'E310000000802'
ORDER BY T.FECHA_CREACION DESC;

/* C. Todos los campos reales de cada tabla - evidencia de esquema */
SELECT TRIM(F.RDB$RELATION_NAME) AS TABLA,
       F.RDB$FIELD_POSITION AS POSICION,
       TRIM(F.RDB$FIELD_NAME) AS CAMPO,
       TRIM(F.RDB$FIELD_SOURCE) AS TIPO_INTERNO
FROM RDB$RELATION_FIELDS F
WHERE F.RDB$RELATION_NAME IN ('NCF_ASIGNADOS', 'VENTAS_MAST')
ORDER BY F.RDB$RELATION_NAME, F.RDB$FIELD_POSITION;

/* D. Origen del procedimiento de persistencia legacy */
SELECT TRIM(P.RDB$PROCEDURE_NAME) AS PROCEDIMIENTO,
       P.RDB$PROCEDURE_SOURCE AS CODIGO_SQL
FROM RDB$PROCEDURES P
WHERE P.RDB$PROCEDURE_NAME = 'SP_ECF_UPDATE_ESTADO';

/* E. Firma del procedimiento (tipos y orden de parámetros) */
SELECT TRIM(P.RDB$PROCEDURE_NAME) AS PROCEDIMIENTO,
       PP.RDB$PARAMETER_NUMBER AS POSICION,
       PP.RDB$PARAMETER_TYPE AS DIRECCION,
       TRIM(PP.RDB$PARAMETER_NAME) AS PARAMETRO,
       TRIM(PP.RDB$FIELD_SOURCE) AS TIPO_INTERNO
FROM RDB$PROCEDURES P
JOIN RDB$PROCEDURE_PARAMETERS PP
  ON PP.RDB$PROCEDURE_NAME = P.RDB$PROCEDURE_NAME
WHERE P.RDB$PROCEDURE_NAME = 'SP_ECF_UPDATE_ESTADO'
ORDER BY PP.RDB$PARAMETER_TYPE, PP.RDB$PARAMETER_NUMBER;
